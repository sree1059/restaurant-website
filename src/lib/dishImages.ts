export function getDishImage(dishName: string, category?: string): string {
  if (DISH_IMAGES[dishName]) {
    return DISH_IMAGES[dishName];
  }

  const nameLower = dishName.toLowerCase();
  for (const [key, url] of Object.entries(DISH_IMAGES)) {
    if (nameLower.includes(key.toLowerCase()) || key.toLowerCase().includes(nameLower)) {
      return url;
    }
  }

  if (nameLower.includes("biryani") || nameLower.includes("pulao")) {
    return "https://images.unsplash.com/photo-1589302168068-964664d93dc0?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("paneer")) {
    return "https://images.unsplash.com/photo-1567188040759-fb8a883dc6d8?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("mutton") || nameLower.includes("mamsam") || nameLower.includes("keema")) {
    return "https://images.unsplash.com/photo-1603894584373-5ac82b2ae398?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("chicken") || nameLower.includes("kodi")) {
    return "https://images.unsplash.com/photo-1610057099443-fde8c4d50f91?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("fish") || nameLower.includes("chepa") || nameLower.includes("prawn") || nameLower.includes("royy")) {
    return "https://images.unsplash.com/photo-1559742811-822873691df8?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("soup") || nameLower.includes("rasam") || nameLower.includes("shorba")) {
    return "https://images.unsplash.com/photo-1547592166-23ac45744acd?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("noodle") || nameLower.includes("noodles")) {
    return "https://images.unsplash.com/photo-1585032226651-759b368d7246?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("rice")) {
    return "https://images.unsplash.com/photo-1512058564366-18510be2db19?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("roti") || nameLower.includes("naan") || nameLower.includes("parota") || nameLower.includes("kulcha")) {
    return "https://images.unsplash.com/photo-1601050690597-df0568f70950?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }
  if (nameLower.includes("sweet") || nameLower.includes("jamun") || nameLower.includes("ice cream") || nameLower.includes("dessert")) {
    return "https://images.unsplash.com/photo-1633383718081-22ac93e3db65?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
  }

  return "https://images.unsplash.com/photo-1546833999-b9f581a1996d?crop=entropy&cs=srgb&fm=jpg&q=85&w=800";
}
